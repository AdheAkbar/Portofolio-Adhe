export const playCelebrationChime = () => {
  if (isMuted) return;
  try {
    const notes = [523.25, 659.25, 783.99, 1046.50]; // C5, E5, G5, C6
    notes.forEach((freq, idx) => {
      setTimeout(() => {
        playTactileClick(freq, 'sine', 0.18);
      }, idx * 70);
    });
  } catch (e) {}
};
